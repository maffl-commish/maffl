#!/usr/bin/env python3
"""Generate key-dates-data.js from the hand-kept gold file data/MAFFL_Key_Dates_<year>.csv.

key-dates-data.js is DERIVED. Never hand-edit it: change the CSV and re-run
    python3 _ops/scripts/gen_key_dates.py            # write
    python3 _ops/scripts/gen_key_dates.py --check    # exit 1 if the .js is stale

weekly.html reads it to build the Key Dates strip (design: _ops/docs/KEY_DATES_DESIGN.md).
"""
import csv
import json
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
YEAR = 2026
SRC = ROOT / "data" / f"MAFFL_Key_Dates_{YEAR}.csv"
OUT = ROOT / "key-dates-data.js"

COLS = ["id", "label", "due", "when", "kind", "tier", "lead_days", "note", "link"]
KINDS = {"deadline", "event"}
TIERS = {"All", "Upper", "Lower"}


def load():
    with SRC.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != COLS:
            sys.exit(f"{SRC.name}: header must be {','.join(COLS)} (got {reader.fieldnames})")
        rows, seen = [], set()
        for n, r in enumerate(reader, start=2):
            where = f"{SRC.name} line {n}"
            if not r["id"] or r["id"] in seen:
                sys.exit(f"{where}: missing or duplicate id {r['id']!r}")
            seen.add(r["id"])
            try:
                due = datetime.fromisoformat(r["due"])
            except ValueError:
                sys.exit(f"{where}: due {r['due']!r} is not ISO with an offset (e.g. 2026-12-02T12:00-05:00)")
            if due.tzinfo is None:
                sys.exit(f"{where}: due needs an ET offset (-04:00 or -05:00)")
            if r["kind"] not in KINDS:
                sys.exit(f"{where}: kind must be one of {sorted(KINDS)}")
            if r["tier"] not in TIERS:
                sys.exit(f"{where}: tier must be one of {sorted(TIERS)}")
            lead = int(r["lead_days"] or 21)
            if not r["label"] or not r["when"]:
                sys.exit(f"{where}: label and when are required")
            rows.append({
                "id": r["id"],
                "label": r["label"],
                "due": r["due"],
                "dueMs": int(due.timestamp() * 1000),
                "when": r["when"],
                "kind": r["kind"],
                "tier": r["tier"],
                "leadDays": lead,
                "note": r["note"],
                "link": r["link"],
            })
    rows.sort(key=lambda x: x["dueMs"])
    return rows


def render(rows):
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    return (
        "/* GENERATED by _ops/scripts/gen_key_dates.py from "
        f"data/{SRC.name}. DO NOT HAND-EDIT. */\n"
        f"window.MAFFL_KEY_DATES = [\n{body}\n];\n"
    )


def main():
    text = render(load())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is stale; run python3 _ops/scripts/gen_key_dates.py")
            sys.exit(1)
        print(f"{OUT.name} OK")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
