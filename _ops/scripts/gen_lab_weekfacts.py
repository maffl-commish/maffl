#!/usr/bin/env python3
"""Build lab/weekfacts-data.js from the robot's weekly ESPN pulls (_ops/inbox/MAFFL_2026_WeekNN_espn.md).

DERIVED, lab-only: feeds the app prototype's quiz cards (bench blunders, top individual score, FAAB bids,
bench-beat-every-starter). Never hand-edit the output; re-run this after each weekly pull:
    python3 _ops/scripts/gen_lab_weekfacts.py
"""
import glob, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "lab", "weekfacts-data.js")

def num(s):
    try: return float(s)
    except Exception: return None

def parse(path):
    txt = open(path, encoding="utf-8-sig").read()
    wk = int(re.search(r"Week(\d+)_espn", path).group(1))
    facts = {"week": wk, "missed": [], "benchBeatAll": [], "top": [], "indHigh": [], "bids": []}
    # MISSED CALLS — Upper/Lower: "- Team: benched P. Name (POS, pts) · started Q. Name (SLOT, pts) [shuffle] · cost X; ..."
    for tier_m in re.finditer(r"MISSED CALLS — (Upper|Lower)[^\n]*\n((?:- [^\n]*\n)+)", txt):
        tier = tier_m.group(1)[0]
        for line in tier_m.group(2).strip().splitlines():
            m = re.match(r"- (.+?): (.*)$", line)
            if not m or "perfect lineup" in m.group(2): continue
            team = m.group(1)
            for call in m.group(2).split("; "):
                c = re.match(r"benched (.+?) \(([^,]+), ([\d.]+)\) · (?:started (.+?) \(([^,]+), ([\d.]+)\)|filled an empty slot)(?: \[shuffle\])? · cost ([\d.]+)", call)
                if not c: continue
                facts["missed"].append({"tier": tier, "team": team, "player": c.group(1), "pos": c.group(2), "pts": num(c.group(3)),
                                        "over": c.group(4) or "", "overPts": num(c.group(6)) or 0, "cost": num(c.group(7)), "shuffle": "[shuffle]" in call})
    for m in re.finditer(r"^- (.+?): benched (.+?) scored ([\d.]+), more than any starter \(best starter ([\d.]+)\)", txt, re.M):
        facts["benchBeatAll"].append({"team": m.group(1), "player": m.group(2), "pts": num(m.group(3)), "bestStarter": num(m.group(4))})
    sec = re.search(r"### 2a\. Top performers\s*```(.*?)```", txt, re.S)
    if sec:
        for line in sec.group(1).strip().splitlines()[1:]:
            p = line.split(",")
            if len(p) >= 9:
                facts["top"].append({"tier": p[2][0], "team": p[3], "owner": p[4], "rank": int(p[5]), "player": p[6], "pos": p[7], "pts": num(p[8])})
    for m in re.finditer(r"INDIVIDUAL HIGH — (Upper|Lower): (.+?), (.+?), ([\d.]+)", txt):
        facts["indHigh"].append({"tier": m.group(1)[0], "player": m.group(2), "team": m.group(3), "pts": num(m.group(4))})
    tb = re.search(r"TOP BIDS: (.*?)(?: · TRADES|\n)", txt)
    if tb:
        for m in re.finditer(r"\$(\d+) (.+?) \((.+?), (Upper|Lower)\)", tb.group(1)):
            facts["bids"].append({"amount": int(m.group(1)), "player": m.group(2), "team": m.group(3), "tier": m.group(4)[0]})
    return facts

def main():
    weeks = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "_ops", "inbox", "MAFFL_2026_Week*_espn.md"))):
        f = parse(path)
        weeks[f["week"]] = f
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* GENERATED by _ops/scripts/gen_lab_weekfacts.py from _ops/inbox/*_espn.md. DO NOT HAND-EDIT. Lab only. */\n")
        fh.write("window.WEEKFACTS = " + json.dumps(weeks, ensure_ascii=False, separators=(",", ":")) + ";\n")
    for w, f in sorted(weeks.items()):
        print(f"Week {w}: {len(f['missed'])} missed calls, {len(f['benchBeatAll'])} bench>starters, {len(f['top'])} top performers, {len(f['indHigh'])} highs, {len(f['bids'])} bids")

if __name__ == "__main__":
    main()
